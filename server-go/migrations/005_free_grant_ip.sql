-- 005_free_grant_ip.sql —— 免费额度发放的**明文客户端 IP**。由 museframe_owner 执行。
--
-- 背景：free_grants 只存 ip_hash（sha256(ip + IP_HASH_SALT) 的前 24 位十六进制）。
-- 哈希对**限流**是够的（同一个 IP 哈希到同一个桶），但对**运营**完全不够：
--   · 「这 40 个账号是不是同一个人在刷」—— 哈希能看出「是同一个来源」，
--     但看不出那个来源是机房、是某个校园网出口、还是客服同事自己在测；
--   · 「把这个 IP 报给 Cloudflare 拦一下」—— 拿哈希报不了；
--   · 盐一换（换过一次 ADMIN_TOKEN 就可能连带换过），历史哈希全部对不上，
--     此前那些行就永久失去了可解释性。
-- 所以这里新增一列**明文 IP**，后台直接显示。这是一个只有管理员令牌打得开的
-- 自家后台，看自家的发放记录里那个请求是从哪个地址来的。
--
-- ip_hash 保留不动：24h 滚动上限的计数与去重还走它（有索引，且对历史行连续）。
--
-- 可空：① 历史行没有这个值，永远是 NULL；② 取不到客户端地址时（直连、
-- 代理头不可信）也必须允许写入 —— 把它设成 NOT NULL 等于让「发不出免费额度」
-- 这种用户可见的故障去替一列运营字段背锅。
--
-- 幂等：可重复执行（IF NOT EXISTS）。
--
-- 🔴 旧镜像兼容：加一列可空列对**正在运行的旧镜像**完全透明（它的 INSERT 列表
--    里没有这一列，PG 按默认值 NULL 填）。所以这个迁移可以在发版**之前**单独执行，
--    不需要停机，也不需要和镜像切换对齐。反向也成立：回滚到旧镜像后这一列
--    只是不再被写入，已有的值不受影响。
--
-- 🔴 列权限：002_grants.sql 的 GRANT ... ON ALL TABLES 是**表级**授权，
--    表级 DML 权限自动覆盖后加的列，所以这里不需要再 GRANT 一次。

BEGIN;

ALTER TABLE free_grants ADD COLUMN IF NOT EXISTS ip text;

-- 刻意**不建索引**：这一列的读法只有两种 —— 后台按用户看那几行、
-- 数据库浏览器整表翻页，两者都不按 ip 过滤。限流计数仍然走 ip_hash 上的索引。

COMMIT;
